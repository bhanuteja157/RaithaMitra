def get_crop_storage_profile(crop_name: str) -> Dict[str, Any]:
    """Return exact or closest normalized crop profile, with honest fallback metadata if unlisted."""
    key = (crop_name or "").strip().lower()
    aliases = {
        "rice": "Paddy",
        "paddy": "Paddy",
        "corn": "Maize",
        "maize": "Maize",
        "finger millet": "Ragi",
        "ragi": "Ragi",
        "chili": "Chilli",
        "chilli": "Chilli",
        "pepper": "Chilli",
        "peanut": "Groundnut",
        "groundnut": "Groundnut",
        "grape": "Grapes",
        "grapes": "Grapes",
        "tomatoes": "Tomato",
        "potatoes": "Potato",
        "onions": "Onion",
        "bananas": "Banana",
        "mangoes": "Mango",
        "carrots": "Carrot",
        "cabbages": "Cabbage",
    }
    canonical = aliases.get(key)
    if not canonical:
        for k in STORAGE_KNOWLEDGE_BASE:
            if k.lower() == key or k.lower() in key:
                canonical = k
                break
    if canonical and canonical in STORAGE_KNOWLEDGE_BASE:
        return {**STORAGE_KNOWLEDGE_BASE[canonical], "is_listed_crop": True}

    return {
        "crop": crop_name or "General Produce",
        "category": "Unlisted Crop (General Guidance)",
        "requires_refrigeration": False,
        "recommended_temp_c": {"min": 12.0, "max": 20.0, "note": "General cool-shade range; verify crop-specific ICAR/NHB manual"},
        "recommended_rh_pct": {"min": 65.0, "max": 85.0},
        "ambient_shelf_life_days": {"min": 3, "max": 10},
        "optimal_shelf_life_days": {"min": 7, "max": 21},
        "suitable_storage_methods": ["Clean Ventilated Shade Storage", "Consult KVK / NHB Crop Manual"],
        "chilling_injury_sensitivity": "Unknown for unlisted crop — avoid <10°C unless verified",
        "chilling_threshold_c": 10.0,
        "moisture_sensitivity": "Avoid surface moisture and condensation",
        "ventilation_requirements": "Maintain clean airflow",
        "ethylene_sensitivity": "Unknown — isolate from ripe fruits",
        "packaging": "Clean ventilated crates",
        "maturity_guidance": "Sort damaged units prior to storage.",
        "references": ["General Post-Harvest Good Practice (FAO) — crop-specific profile not yet listed"],
        "is_listed_crop": False,
    }


def list_supported_crops() -> List[Dict[str, Any]]:
    return [STORAGE_KNOWLEDGE_BASE[k] for k in sorted(STORAGE_KNOWLEDGE_BASE.keys())]
